// Builds a single-file t3-term binary for this machine (or COMPILE_TARGET).
//   bun scripts/build.ts [outfile]
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "..");
const platformPackage: Record<string, string> = {
  "win32-x64": "win32-x64-msvc",
  "win32-arm64": "win32-arm64-msvc",
  "darwin-arm64": "darwin-arm64",
  "linux-x64": "linux-x64-gnu",
};
const key = `${process.platform}-${process.arch}`;
const suffix = platformPackage[key];
if (!suffix) throw new Error(`gpuix ships no native addon for ${key}`);

// The platform package is an optional dependency of @gpuix/native, so resolve it
// from there; with isolated installs the app itself cannot see it.
const nativeDir = dirname(require.resolve("@gpuix/native/package.json"));
const addon = join(
  dirname(require.resolve(`@gpuix/native-${suffix}/package.json`, { paths: [nativeDir] })),
  `gpuix-native.${suffix}.node`,
).replaceAll("\\", "/");
const embedPath = join(root, "src/generated/nativeEmbed.ts");
const stub = `// Replaced by scripts/build.ts for a compiled binary. In development the
// native addon resolves from node_modules, so there is nothing to embed.
const nativePath: string | null = null;
export default nativePath;
`;
writeFileSync(
  embedPath,
  `// Generated by scripts/build.ts for ${key}.
import nativePath from ${JSON.stringify(addon)} with { type: "file" };
export default nativePath as string | null;
`,
);
// The licenses page reads the repository at runtime in development; a binary
// carries the manifest instead.
const licensePath = join(root, "src/generated/licenseManifest.ts");
const licenseStub = `// Replaced by scripts/build.ts for a compiled binary, which cannot read the
// repository at runtime. In development the page generates the manifest itself.
const embeddedManifest: unknown = null;
export default embeddedManifest;
`;
const licenses = await import("../src/settings/licenses/manifest.ts");
const generator = (await import(licenses.generatorUrl)) as {
  generateThirdPartyLicenseManifest: (input: object) => Promise<unknown>;
};
const manifest = await generator.generateThirdPartyLicenseManifest({
  packageManifests: [{ bundle: licenses.LICENSE_BUNDLE, path: licenses.appPackageJson }],
  bundleName: licenses.LICENSE_BUNDLE,
  configFile: licenses.configFile,
  allowMissingGeneratedNotices: true,
});
writeFileSync(
  licensePath,
  `// Generated by scripts/build.ts.
const embeddedManifest: unknown = ${JSON.stringify(manifest)};
export default embeddedManifest;
`,
);
const outfile = process.argv[2] ?? join(root, "dist", process.platform === "win32" ? "t3-term.exe" : "t3-term");
try {
  const result = await Bun.build({
    entrypoints: [join(root, "src/entry.ts"), join(root, "src/panels/code/highlightWorker.ts")],
    compile: { outfile },
    minify: true,
    // React picks its development or production build from NODE_ENV. Without
    // this the binary shipped React's development build: every render also
    // records the debug info DevTools reads, about twice the JS work per commit.
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  console.log(`wrote ${outfile}`);
} finally {
  writeFileSync(embedPath, stub);
  writeFileSync(licensePath, licenseStub);
}
