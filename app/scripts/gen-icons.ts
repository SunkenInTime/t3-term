// Embeds every lucide-static icon as a string so `bun build --compile` carries them.
// gpuix tints an svg by its alpha, so strokes are forced to black.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "../node_modules/lucide-static/icons");
const entries: Array<[string, string]> = [];
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith(".svg")) continue;
  const body = readFileSync(join(dir, file), "utf8")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s*class="[^"]*"/, "")
    .replace(/currentColor/g, "#000")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  entries.push([file.slice(0, -4), body]);
}
const out =
  "// Generated by scripts/gen-icons.ts from lucide-static. Do not edit.\n" +
  `export const LUCIDE = {\n${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n} as const;\n` +
  "export type LucideName = keyof typeof LUCIDE;\n";
writeFileSync(join(import.meta.dir, "../src/ui/lucide.gen.ts"), out);
console.log(`wrote ${entries.length} icons`);
